import { PROFILES } from "../src/composition/profiles.ts";
import type { Capability } from "../src/core/capability.ts";

/** Any named grouping of capabilities; tests supply kinds that are not real project kinds. */
type Profiles = Record<string, readonly Capability[]>;

export const REFERENCE_START = "<!-- capability-reference:start -->";
export const REFERENCE_END = "<!-- capability-reference:end -->";
export const INVENTORY_START = "<!-- capability-inventory:start -->";
export const INVENTORY_END = "<!-- capability-inventory:end -->";
export const REFERENCE_FILES = ["README.md", "specs/02-project-functions.md"];

/** Keeps Biome's Markdown formatter from padding generated tables. */
const BIOME_IGNORE = "<!-- biome-ignore format: generated table -->";

const cell = (text: string) =>
  text.replaceAll("|", "&#124;").replace(/\r?\n/g, " ");

function selection(capability: Capability): string {
  const policy = capability.selection;
  if (!policy) return "Required";
  return [
    policy.default ? "Default" : "Opt-in",
    ...(policy.with ? [`\`--with-functions ${capability.name}\``] : []),
    ...(policy.without ? [`\`--without-functions ${capability.name}\``] : []),
    ...(!policy.default ? ["`--preset all`"] : []),
  ].join("; ");
}

export function renderCapabilityReference(
  profiles: Profiles = PROFILES,
): string {
  const rows = new Map<string, { kinds: string[]; cells: string[] }>();
  for (const [kind, capabilities] of Object.entries(profiles)) {
    for (const capability of capabilities) {
      const docs = capability.documentation;
      if (!docs.tools.length)
        throw new Error(
          `${kind}/${capability.name}: document at least one tool or format`,
        );
      const tools = docs.tools
        .map(({ name, url, purpose }) => {
          if (!name.trim() || !purpose.trim() || !/^https:\/\//.test(url))
            throw new Error(
              `${kind}/${capability.name}: tools need a name, HTTPS link, and purpose`,
            );
          return `[${name}](${url}) — ${purpose}`;
        })
        .join("<br>");
      const verbs = (["init", "update", "validate"] as const).map((verb) => {
        const operation = capability[verb];
        const description = docs[verb];
        if (typeof operation !== "function") {
          if (description !== undefined)
            throw new Error(
              `${kind}/${capability.name}.${verb}: use the no-op reason, not duplicated documentation`,
            );
          return `**No-op:** ${operation.reason}`;
        }
        if (!description?.trim())
          throw new Error(
            `${kind}/${capability.name}.${verb}: document the implemented verb`,
          );
        return description;
      });
      const cells = [
        `\`${capability.name}\``,
        selection(capability),
        tools,
        ...verbs,
      ];
      const key = JSON.stringify(cells);
      const existing = rows.get(key);
      if (existing) existing.kinds.push(kind);
      else rows.set(key, { kinds: [kind], cells });
    }
  }
  return [
    REFERENCE_START,
    "<!-- Generated by bun run scripts/refresh-capability-docs.ts; do not edit this block. -->",
    BIOME_IGNORE,
    "| Kinds | Capability | Selection | Tool / purpose | Capability init | Update | Validate |",
    "|---|---|---|---|---|---|---|",
    ...Array.from(
      rows.values(),
      ({ kinds, cells }) =>
        `| ${[kinds.map((kind) => `\`${kind}\``).join(", "), ...cells].map(cell).join(" | ")} |`,
    ),
    REFERENCE_END,
  ].join("\n");
}

export function renderCapabilityInventory(
  profiles: Profiles = PROFILES,
): string {
  return [
    INVENTORY_START,
    "<!-- Generated by bun run scripts/refresh-capability-docs.ts; do not edit this block. -->",
    BIOME_IGNORE,
    "| Kind | Capabilities in execution order (including optional capabilities) |",
    "|---|---|",
    ...Object.entries(profiles).map(
      ([kind, capabilities]) =>
        `| \`${kind}\` | ${capabilities.map((capability) => `\`${capability.name}\`${capability.selection ? ` (${selection(capability)})` : ""}`).join(", ")} |`,
    ),
    INVENTORY_END,
  ].join("\n");
}

/** Replace exactly one marked block; refuse missing or ambiguous markers before writing. */
export function replaceGeneratedBlock(
  contents: string,
  start: string,
  end: string,
  block: string,
): string {
  const from = contents.indexOf(start);
  const to = contents.indexOf(end);
  if (
    from < 0 ||
    to < from ||
    contents.indexOf(start, from + start.length) !== -1 ||
    contents.indexOf(end, to + end.length) !== -1
  )
    throw new Error(`Expected exactly one ordered ${start} / ${end} block`);
  return contents.slice(0, from) + block + contents.slice(to + end.length);
}
